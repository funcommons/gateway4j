def parse_line(raw):
    """解析一行 Playwright list reporter 输出。
    格式: '  ✓   1 [chromium] › e2e-regression/xx.spec.ts:1:1 › BL-01 认证与登录 › 01-01 标题 (672ms)'"""
    if ('\u2713' not in raw) and ('\u2718' not in raw):
        return None
    parts = [x.strip() for x in raw.split('\u203a')]
    if len(parts) < 4:
        return None
    head = parts[0]
    mark = '\u2713' if '\u2713' in head else '\u2718'
    cid = re.match(r'^(\d\d-\d\d)\b', parts[3])
    if not cid:
        return None
    title = re.sub(r'\(\d+(\.\d+)?m?s\)$', '', parts[3]).strip()
    # parts[3] 形如 "01-01 标题"
    title = re.sub(r'^\d\d-\d\d\s*', '', title).strip()
    return mark, cid.group(1), title


results = OrderedDict()
for raw in open(LOG, encoding='utf-8', errors='replace'):
    r = parse_line(raw)
    if not r:
        continue
    mark, cid, title = r
    results[cid] = ('PASS' if mark == '\u2713' else 'FAIL', title)

# 输出 Markdown
lines = []
by_line = OrderedDict()
for cid, (st, title) in results.items():
    line_id = 'BL-' + cid[:2]
    by_line.setdefault(line_id, []).append((cid, st, title))

print('| 业务线 | 用例 | 结论 | 缺陷 | 说明 |')
