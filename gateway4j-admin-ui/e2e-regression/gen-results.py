total = pass_n = fail_n = 0
for line_id, (folder, lname) in LINE_META.items():
    cases = by_line.get(line_id, [])
    if not cases:
        continue
    p = sum(1 for c in cases if c[1] == 'PASS')
    f = len(cases) - p
    total += len(cases); pass_n += p; fail_n += f
    print(f'| **{line_id} {lname}** | {len(cases)} | {p} 通过 / {f} 失败 | — | 截图目录 `screenshots/{folder}/` |')
    for cid, st, title in cases:
        defect, note = CASE_META.get(cid, ('-', ''))
        icon = '✅ PASS' if st == 'PASS' else '❌ FAIL'
        dcell = f'**{defect}**' if defect != '-' else '—'
        lines.append(f'| {cid} | {title} | {icon} | {dcell} | {note} |')
print()
print('TOTALS', total, pass_n, fail_n)
print()
print('\n'.join(lines))
