package fun.commons.gateway4j.plugin.builtins.logging.elasticsearch;

import fun.commons.gateway4j.plugin.api.PluginChain;
import fun.commons.gateway4j.plugin.api.PluginConfig;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.mock.http.server.reactive.MockServerHttpRequest;
import org.springframework.mock.web.server.MockServerWebExchange;
import reactor.core.publisher.Mono;
import reactor.test.StepVerifier;

import static org.junit.jupiter.api.Assertions.*;

class LoggingElasticsearchPluginTest {

    private LoggingElasticsearchPlugin plugin;

    @BeforeEach
    void setUp() {
        plugin = new LoggingElasticsearchPlugin();
    }

    private MockServerWebExchange createExchange(String path) {
        MockServerHttpRequest request = MockServerHttpRequest.get(path).build();
        return MockServerWebExchange.builder(request).build();
    }

    private PluginChain passThroughChain() {
        return exchange -> Mono.empty();
    }

    @Test
    void noConfigPassesThrough() {
        MockServerWebExchange exchange = createExchange("/test");
        StepVerifier.create(plugin.execute(exchange, passThroughChain())).verifyComplete();
    }

    @Test
    void withConfigPassesThroughEvenWithoutES() {
        plugin.onConfigChange(new PluginConfig("logging-es",
                "{\"host\":\"localhost\",\"port\":9200,\"indexName\":\"gateway-logs\"}", 1));

        MockServerWebExchange exchange = createExchange("/test");
        StepVerifier.create(plugin.execute(exchange, passThroughChain())).verifyComplete();
    }

    @Test
    void pluginIdAndPhase() {
        assertEquals("logging-es", plugin.pluginId());
        assertEquals("PRE", plugin.phase());
    }
}
